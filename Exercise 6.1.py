# 1. Membuat dictionary 'person'
person = {
    'first_name': 'Eljia',
    'last_name': 'Soedjono',
    'age': 19,
    'city': 'Surakarta'
}

# 2. Mencetak setiap informasi dari dictionary
print(f"Nama Depan      : {person['first_name'].title()}")
print(f"Nama Belakang   : {person['last_name'].title()}")
print(f"Umur            : {person['age']} tahun")
print(f"Kota            : {person['city']}")