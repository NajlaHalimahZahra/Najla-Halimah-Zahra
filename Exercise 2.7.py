name = "\t\t Roxana Agriche \n\t"

print("Asli dengan spasi/tab:")
print(name)

print("\nPakai lstrip (hapus spasi kiri):")
print(name.lstrip())

print("\nPakai rstrip (hapus spasi kanan):")
print(name.rstrip())

print("\nPakai strip (hapus semua spasi di kiri & kanan):")
print(name.strip())