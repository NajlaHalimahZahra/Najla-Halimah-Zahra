# 1. List tiga hewan dengan karakteristik mirip 
animals = ['singa', 'kucing', 'harimau', 'puma', 'jaguar']

# 2. Menggunakan for loop untuk mencetak pernyataan tentang setiap hewan
for animal in animals:
    print(f"Seekor {animal} merupakan hewan karnivora.")

# 3. Baris tambahan di luar loop (menyatakan kesamaan karakteristik)
