# Ubah nilai menjadi 'green', 'yellow', atau 'red' untuk mengetes setiap kondisi
alien_color = 'yellow'

print(f"Warna alien saat ini: {alien_color}")

# Rangkaian percabangan if-elif-else
if alien_color == 'green':
    print("You just earned 5 points!")
elif alien_color == 'yellow':
    print("You just earned 10 points!")
else:
    print("You just earned 15 points!")