# 1. List jenis-jenis pizza favorit
pizzas = ['pepperoni', 'cheese', 'meat lover', ]

# 2. Menggunakan for loop untuk mencetak kalimat untuk setiap pizza
for pizza in pizzas:
    print(f"I like {pizza} pizza!")

# 3. Baris tambahan di luar loop (dieksekusi sekali setelah perulangan selesai)
print("\nI really love pizza!")